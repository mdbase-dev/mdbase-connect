#!/usr/bin/env node
/** BUILD ONLY. Generates the create-only `.generated/kms-collections.ts` that
 * Wrangler's fixed `#hosted-kms-collections` alias requires for a deploy build.
 *
 *   node build-kms-allowlist.mjs --collections FILE --sha256 HEX
 *     (--previous FILE --previous-sha256 HEX | --initial)
 *     [--retire FILE --retire-sha256 HEX] [--role hosted|escrow]
 *
 * Every list is canonical allowlist text (src/custody/kms-allowlist.ts) and every
 * digest comes from the authenticated deploy manifest: the new allowlist, the
 * allowlist the currently deployed version serves, and an optional retire list.
 * Refuses a digest mismatch, a non-canonical or oversized list, and any change
 * that stops serving a previously served collection without naming it in the
 * retire list. `--initial` (no previous allowlist) is only for a deployment that
 * has never served one. No network, defaults or overwrite.
 *
 * Allow-all: a collections file containing exactly "*\n" builds the allow-all
 * module, which requires `--role hosted|escrow` (the CP deployment it is for)
 * and records it in the module; `--role` is refused for an exact list. Any
 * list -> allow-all is growth (no retire list); allow-all -> list is refused
 * (`kms_allowlist_all_shrinks`). The Worker additionally admits allow-all only
 * in a staging/production CP deployment whose SERVICE_KIND equals the role.
 *
 * Node 24 (type stripping) runs the shared TypeScript module directly.
 */
import { lstatSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { KMS_ALLOWLIST_SCHEMA, KmsAllowlist, MAX_KMS_COLLECTIONS, cumulativeKmsAllowlist } from "./src/custody/kms-allowlist.ts";
const ROLES = ["hosted", "escrow"];

const names = { "--collections": "collections", "--sha256": "sha256", "--previous": "previous", "--previous-sha256": "previousSha256",
  "--retire": "retire", "--retire-sha256": "retireSha256", "--initial": "initial", "--role": "role" };
const MAX_BYTES = MAX_KMS_COLLECTIONS * 37;

function read(path, digest) {
  const info = lstatSync(path);
  if (!info.isFile() || info.size > MAX_BYTES) throw new Error("kms_allowlist_invalid");
  return KmsAllowlist.parse(readFileSync(path, "latin1"), digest);
}

try {
  const args = process.argv.slice(2), options = {};
  for (let i = 0; i < args.length; i++) {
    const key = names[args[i]];
    if (!key || Object.hasOwn(options, key)) throw new Error("usage");
    if (key === "initial") { options.initial = true; continue; }
    if (i + 1 >= args.length) throw new Error("usage");
    options[key] = args[++i];
  }
  const pair = (file, digest) => (options[file] === undefined) === (options[digest] === undefined);
  if (!options.collections || !options.sha256 || !pair("previous", "previousSha256") || !pair("retire", "retireSha256")
      || (options.initial === true) === (options.previous !== undefined) || (options.initial && options.retire !== undefined)) throw new Error("usage");
  const next = read(options.collections, options.sha256);
  // Allow-all names exactly one CP role; an exact list never carries one.
  if (next.all ? !ROLES.includes(options.role) : options.role !== undefined) throw new Error("kms_allowlist_role_invalid");
  let change = { added: next.all ? "all" : next.size, retired: 0 };
  if (!options.initial) {
    const previous = read(options.previous, options.previousSha256);
    const retire = options.retire === undefined ? null : read(options.retire, options.retireSha256);
    change = cumulativeKmsAllowlist(previous, next, retire);
  }
  const directory = resolve(dirname(fileURLToPath(import.meta.url)), ".generated");
  mkdirSync(directory, { recursive: true });
  const bundle = { schema: KMS_ALLOWLIST_SCHEMA, sha256: next.sha256, text: next.text, ...(next.all ? { role: options.role } : {}) };
  const source = "// GENERATED by build-kms-allowlist.mjs. Do not edit; regenerate from the deploy manifest.\n"
    + `const bundle = Object.freeze(${JSON.stringify(bundle)});\n`
    + "export function kmsCollections() { return bundle; }\n";
  writeFileSync(resolve(directory, "kms-collections.ts"), source, { flag: "wx", mode: 0o644 });
  console.log(JSON.stringify({ schema: KMS_ALLOWLIST_SCHEMA, sha256: next.sha256, count: next.all ? null : next.size,
    ...(next.all ? { mode: "all", role: options.role } : {}),
    previous_sha256: options.initial ? null : options.previousSha256, retire_sha256: options.retireSha256 ?? null, ...change }));
} catch (error) {
  const code = error instanceof Error && /^kms_allowlist_[a-z_]+$/.test(error.message) ? error.message : "kms_allowlist_build_refused";
  console.error(`hosted KMS allowlist build refused: ${code}`);
  process.exitCode = 1;
}
