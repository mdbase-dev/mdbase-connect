import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const stylesheetPath = require.resolve("@phosphor-icons/web/regular");
const outputPath = resolve(dirname(fileURLToPath(import.meta.url)), "../src/phosphor-icon-names.generated.ts");
const stylesheetOutputPath = resolve(dirname(fileURLToPath(import.meta.url)), "../src/phosphor-icons.generated.css");
const stylesheet = await readFile(stylesheetPath, "utf8");
const names = [...stylesheet.matchAll(/\.ph\.ph-([a-z0-9-]+):before/g)]
  .map((match) => match[1])
  .sort((left, right) => left.localeCompare(right));

if (!names.length) throw new Error("No Phosphor icon names were found.");

await writeFile(
  outputPath,
  `// Generated by scripts/write-phosphor-icon-names.mjs. Do not edit by hand.\n`
    + `export const PHOSPHOR_ICON_NAMES = ${JSON.stringify(names)} as const;\n`,
  "utf8"
);

const rulesStart = stylesheet.indexOf(".ph {");
if (rulesStart < 0) throw new Error("The Phosphor base icon rules were not found.");
await writeFile(
  stylesheetOutputPath,
  `/* Generated by scripts/write-phosphor-icon-names.mjs. Do not edit by hand. */\n`
    + `@font-face {\n`
    + `  font-family: "Phosphor";\n`
    + `  src: url("@phosphor-icons/web/regular/Phosphor.woff2") format("woff2");\n`
    + `  font-weight: normal;\n`
    + `  font-style: normal;\n`
    + `  font-display: block;\n`
    + `}\n\n`
    + stylesheet.slice(rulesStart),
  "utf8"
);
