// Precompiles the application manifest JSON Schemas (current and legacy v1) into
// standalone Ajv validators, so consumers validate with the same rules without
// bundling the Ajv compiler. `--check` fails when the committed output is stale.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const protocol = resolve(root, "packages/protocol");
const require = createRequire(resolve(protocol, "package.json"));
const { Ajv2020 } = require("ajv/dist/2020.js");
const addFormats = require("ajv-formats");
const standaloneCode = require("ajv/dist/standalone").default;

const outputPath = resolve(protocol, "src/manifest-validators.generated.ts");
const schema = (name) => JSON.parse(readFileSync(resolve(protocol, "schemas", name), "utf8"));
const current = schema("mdbase-app.schema.json");
const legacy = schema("mdbase-app.legacy-v1.schema.json");

// Exactly the options the runtime validator used before precompilation.
const ajv = new Ajv2020({
  allErrors: true,
  strict: true,
  // `required` may name properties declared by an enclosing oneOf branch.
  strictRequired: false,
  code: { source: true, esm: true }
});
addFormats(ajv, { mode: "full", formats: ["uri"] });
ajv.addSchema(current);
ajv.addSchema(legacy);
const standalone = standaloneCode(ajv, {
  appManifestValidator: String(current.$id),
  legacyAppManifestValidator: String(legacy.$id)
});

// Ajv's ESM standalone output still require()s its runtime helpers. Inline them
// so the generated module has no imports and consumers never bundle Ajv itself.
const formatsSource = readFileSync(require.resolve("ajv-formats/dist/formats"), "utf8");
const declaration = (name) => {
  const match = formatsSource.match(new RegExp(`^const ${name} = .*;$`, "m"));
  if (!match) throw new Error(`ajv-formats no longer declares ${name}`);
  return match[0];
};
const { fullFormats } = require("ajv-formats/dist/formats");
const helpers = new Map([
  [
    'require("ajv-formats/dist/formats").fullFormats.uri',
    `(() => { ${declaration("NOT_URI_FRAGMENT")} ${declaration("URI")} return ${fullFormats.uri.toString()}; })()`
  ],
  ['require("ajv/dist/runtime/ucs2length").default', require("ajv/dist/runtime/ucs2length").default.toString()],
  [
    'require("ajv/dist/runtime/equal").default',
    // Ajv's own equality helper re-exports fast-deep-equal; resolve it from Ajv.
    createRequire(require.resolve("ajv/dist/runtime/equal"))("fast-deep-equal").toString()
  ]
]);
let code = standalone;
for (const [reference, implementation] of helpers) {
  if (!code.includes(reference)) continue;
  code = code.replaceAll(reference, () => `(${implementation})`);
}
if (/\brequire\(/.test(code)) {
  throw new Error(`unhandled runtime import in standalone validators: ${code.match(/require\([^)]*\)/)[0]}`);
}

const source = `// Generated by scripts/generate-manifest-validators.mjs from schemas/mdbase-app.schema.json
// and schemas/mdbase-app.legacy-v1.schema.json. Do not edit.
// @ts-nocheck
/* eslint-disable */
${code}
`;

if (process.argv.includes("--check")) {
  if (readFileSync(outputPath, "utf8") !== source) {
    console.error("manifest validators are stale: run node scripts/generate-manifest-validators.mjs");
    process.exit(1);
  }
} else {
  writeFileSync(outputPath, source);
}
