import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const catalog = JSON.parse(readFileSync(resolve(root, "packages/protocol/schemas/change-events.v1.json"), "utf8"));
if (catalog.version !== 1) throw new Error("Change event catalog version must be 1.");
const types = {
  string: ["string", "String"],
  strings: ["string[]", "Vec<String>"],
  boolean: ["boolean", "bool"],
  object: ["JsonObject", "serde_json::Map<String, Value>"],
  file: ["CollectionFileDescriptor", "CollectionFileDescriptor"]
};
const header = "// Generated by scripts/generate-change-events.mjs. Do not edit directly.\n\n";
let ts = header + 'import type { CollectionFileDescriptor, JsonObject } from "./index.js";\n\n';
let rs = header + "use super::*;\n\n";
ts += `export const CHANGE_EVENT_KINDS = ${JSON.stringify(catalog.events, null, 2)} as const;\n\n`;
ts += "export type KnownCollectionChangeType = keyof typeof CHANGE_EVENT_KINDS;\n\n";
rs += "pub fn collection_change_kind(event_type: &str) -> Option<&'static str> {\n    match event_type {\n";
for (const [id, kind] of Object.entries(catalog.events)) {
  rs += `        ${JSON.stringify(id)} => Some(${JSON.stringify(kind)}),\n`;
}
rs += "        _ => None,\n    }\n}\n\n";
for (const [name, fields] of Object.entries(catalog.payloads)) {
  ts += `/** Optional metadata: older authorities may omit fields; null means unavailable. */\nexport interface ${name} {\n`;
  rs += `#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]\npub struct ${name} {\n`;
  for (const [field, type] of Object.entries(fields)) {
    if (!types[type]) throw new Error(`Unknown payload field type: ${type}`);
    ts += `  ${field}?: ${types[type][0]} | null;\n`;
    rs += `    #[serde(default, skip_serializing_if = "Option::is_none")]\n    pub ${field}: Option<${types[type][1]}>,\n`;
  }
  ts += "}\n\n";
  rs += "}\n\n";
}
for (const [path, source] of [
  ["packages/protocol/src/change-events.ts", ts.trimEnd() + "\n"],
  ["crates/connect-protocol/src/change_events_generated.rs", rs.trimEnd() + "\n"]
]) {
  const absolute = resolve(root, path);
  if (process.argv.includes("--check")) {
    if (readFileSync(absolute, "utf8") !== source) throw new Error(`${path} is stale; run pnpm generate:changes.`);
  } else writeFileSync(absolute, source);
}
